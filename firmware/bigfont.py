_FALLBACK = _GLYPHS["?"]


def has_glyph(ch):
    return ch.upper() in _GLYPHS


def render(ch, cols=20, rows=4, scale=3):
    """Devolve `rows` strings de `cols` caracteres com o caractere ampliado,
    já centralizado horizontalmente e pronto para write_line()."""
    glyph = _GLYPHS.get(ch.upper(), _FALLBACK)
    blank = " " * cols
    out = []
    for row in range(rows):
        if row >= len(glyph):
            out.append(blank)
            continue
        expanded = "".join((_ON if c == "#" else _OFF) * scale for c in glyph[row])
        pad = cols - len(expanded)
        if pad < 0:
            out.append(expanded[:cols])
            continue
        left = pad // 2
        out.append((" " * left) + expanded + (" " * (pad - left)))
    return out
